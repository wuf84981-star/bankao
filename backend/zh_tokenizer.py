def _init_dict() -> None:
    """把专名灌进 jieba。重复调用无害（幂等），只在首次 import 后跑一次。"""
    for w in CUSTOM_WORDS:
        # freq 给 3000（高于默认词频量级）确保不被切碎；词性留空由 jieba 猜
        jieba.add_word(w, freq=3000)


_init_dict()

# 中文停用词表：查询词里这些字不进to_tsquery。
# 为什么不用 PG 侧：PG 的 'simple' 配置不带停用词表（那是 'english' 的
# 事），中文停用词只能我们自己剔——留着「的/了/怎么/什么」这类词会
# 让 to_tsquery 命中一整片无关块，等于没过滤。
# 清单按公考问句实测高频虚词抓，不求全，求够用。
STOPWORDS = frozenset("""
的 了 和 是 在 我 有 就 不 人 都 一 一个 上 也 很 到 说 要 去 你 会 着 没有 看
好 自己 这 那 这个 那个 什么 怎么 怎样 如何 为什么 哪 哪个 多少 可以 可能 应该
我们 你们 他们 它 吗 呢 吧 啊 呀 嘛 哦 嗯 把 被 让 给 从 对 与 及 或 但 但是
而且 因为 所以 如果 虽然 就是 还是 已经 一些 一直 一下 这些 那些 请问 请
怎么 是什么 什么样 帮我 帮忙 谢谢 麻烦
""".split())

# 单字无检索价值（除非它本身就是检索目标，但那时候用向量腿）
_SINGLE_NOISE = frozenset("的了和是在我有就不人都也很到说要去你会着看好这那个么吗呢")

# 英文/数字混排：保留（资料分析里「GDP」「2024」这类必须能命中）
_ALNUM = re.compile(r"[a-zA-Z0-9]+(?:\.\d+)?%?")


def cut_words(text: str) -> list[str]:
    """中文串 → 检索词列表（已去停用词与单字噪声）。

    流程：jieba 精确模式切分 → 剔停用词与单字噪声 → 保留英文数字串。
    「基期量怎么算」→「基期量 / 算」（专名靠词典保住完整）。
    """
    if not text or not text.strip():
        return []
    words: list[str] = []
    for raw in jieba.cut(text.strip()):
        w = raw.strip()
        if not w:
            continue
        # 英文/数字 token 原样留（GPD、2024、3.5%）
        if _ALNUM.fullmatch(w):
            words.append(w.lower())      # 大小写归一，避免 GDP 与 gpd 分成两套词项
            continue
        if w in STOPWORDS or w in _SINGLE_NOISE:
            continue
        if len(w) < 2:                    # 单字虚词与噪声词
            continue
        words.append(w)
    return words


def ts_input(text: str) -> str:
    """中文串 → 可直接喂 PG to_tsvector('simple', …) 的空格分词串。

    为什么空格连接：PG 的 simple 配置按空白切词项，空格就是我们的分词
    边界。中文没空格，所以分词结果必须自带分隔符——不拼这一步，
    PG 会把「基期量算多少」当一整个词项，永远匹配不上任何东西。
    """
    return " ".join(cut_words(text))


def tsquery_from(text: str, *, mode: str = "OR") -> str:
    """中文串 → PG to_tsquery 的查询串。

    默认 OR 而非 AND：「基期量」「现期量」两个词，OR 是并集召回（先捞全
    再靠 RRF 与向量腿合议排序），AND 是交集（「基期量」且「现期量」
    同时出现的块极少，直接把候选清空）。短问句用 AND 召回更准，但问句
    普遍是「X 怎么算」这种多成分结构，AND 几乎必然落空——故默认 OR。
    mode="AND" 留给调用方明确知道该用交集时（如精确专名核查）。

    安全：词内只允许字母数字与 CJK（正则过滤过），拼不出 tsquery 的
    运算符语法，注入不了 '&' ':' '!' 这类符号——分隔符之外的东西
    根本进不来。
    """
    words = cut_words(text)
    if not words:
        return ""
    op = " & " if mode == "AND" else " | "
    return op.join(words)