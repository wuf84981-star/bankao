# ============================================================
# 中文分词腿（zh_tokenizer.py）：讲义全文检索的地基
#
# 为什么有这根：S3校准刀验尸pg_trgm 对中文按 UTF-8 字节剁三元组——
# 「基期量怎么算」对正题块 similarity 被稀释到 0.0275，阈值降到 0.01
# 才勉强放行，关键词腿事实上等于半废（search.py 注释原账）。
# PG 自带分词器（'simple' 等）不切中文词，等于不切——「基期量算多少」
# 原样进去原样出来，永远命中不了「基期量怎么计算」那块讲义。
# 于是分词在 Python 侧做：jieba 切词 → 空格连接 → 交给 PG 的
# to_tsvector('simple', …)。'simple' 只负责把空格分隔的词当词项，
# 不再二次切分——分词权在我们手里，索引照吃。
#
# 纯函数 + 一处全局初始化（与 embedder.py 的懒加载单例同家法）：
# jieba 首次建词典约 0.7s，import 时不建、首次调用时建，之后常驻。
# ============================================================
