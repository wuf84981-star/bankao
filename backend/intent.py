from backend.zh_tokenizer import CUSTOM_WORDS

# 求讲词：用户明确在「要人教」的口吻。宽进没问题——还得同时撞专名才放行。
_ASK_WORDS = (
    "怎么算", "怎么求", "什么意思", "啥意思", "怎么理解", "什么是", "是什么",
    "讲讲", "讲一下", "教我", "解释", "不懂", "没懂", "辨析", "怎么区分",
    "怎么考", "怎么破", "怎么做", "公式", "套路", "例题", "为什么", "如何",
)

# 事务否决词表（施工图给了一票否决权）：沾到一个就不进教学轨。
# 这些全是现工具链的活：排期/打卡/出题/判分/签到/提醒/改设置/资料管理。
# 保守面：「调整」这种词会连带挡掉「增长率怎么调整公式」这类怪句式——
# 挡错了也是低代价方向（事务轨照常能答），不心疼。
_TASK_WORDS = (
    "计划", "排个", "排一下", "帮我排", "安排", "打卡", "出题", "来几道",
    "判分", "签到", "提醒", "几点", "倒计时", "改成", "调整", "设置",
    "上传", "删除", "取消", "绑定", "报名", "积分", "导出",
)

# 图转写头（S7 四刀字面，orchestrator:448 实锤）：OCR 口供不是用户原话，
# 拍照链已有自己的流程（image_turn），不许再进教学轨。
_IMAGE_HEAD = "[拍照汇报·图转写"

_MAX_LEN = 400   # 超过就是粘贴的材料/长文，不是在提问


def is_teaching_question(text: str, *, has_materials: bool) -> bool:
    """True = 走教学轨；False = 走事务轨（原路一字不动）。
    放行条件全AND：有材料可教 + 不是图转写头 + 不太长 + 不带事务否决词
    + 撞见公考专名 + 带求讲口吻。缺任何一个 → False。"""
    if not has_materials:
        return False
    t = (text or "").strip()
    if not t or len(t) > _MAX_LEN:
        return False
    if t.startswith(_IMAGE_HEAD):
        return False
    if any(w in t for w in _TASK_WORDS):
        return False
    if not any(w in t for w in _ASK_WORDS):
        return False
    # 专名单源：与检索腿吃同一本词典（zh_tokenizer 52 词）——
    # 「意图认不出的专名，检索腿也别想认出」，两处必须同进同退
    return any(w in t for w in CUSTOM_WORDS)
