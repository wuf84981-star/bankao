# 一句话：这句话该走教学轨（状态图）还是事务轨（原工具链）？
# 立场（施工图钉死）：**判错走教学轨的代价高**（图依赖讲义检索、六步编排
# 对闲聊完全不合适），判错走事务轨的代价低（工具链本来就宽容）——
# 所以所有拿不准的分支一律 False。
# W4 备料立场：本文件无人 import，W5 教学图上岗才接线——回滚=不接即不存在。
